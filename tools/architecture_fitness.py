#: Documented exception: this is the SINGLE canonical fallback-marker classifier
#: (see its own docstring -- "made this function public in the first place" to
#: stop this exact pattern being duplicated ad hoc elsewhere). It defines the
#: structured contract other code is meant to call into rather than re-parsing
#: reason text itself, so it is excluded from the R3 site count as the sanctioned
#: implementation, not a violation. Revisit when R3 actually lands -- at that
#: point this function's own reason-matching may become the thing R3 replaces.
R3_SANCTIONED_SITES = {("compound.py", "fallback_kind_for_reason")}

#: String methods that recover STRUCTURED DATA (a substring, a position, an
#: index) out of a reason-named string when called ON it, e.g. ``reason.split``
#: or ``reason_body.rsplit``. Widened from the original {split, startswith,
#: endswith} after a real false negative: ``part.rsplit(" -> ", 1)`` inside a
#: (since-removed) hook.py helper recovered a ``(sub_command, matched_rule)``
#: pair the original set could not see would-be-caught receivers for.
_REASON_STRING_METHODS = {
    "split",
    "rsplit",
    "startswith",
    "endswith",
    "partition",
    "rpartition",
    "rindex",
    "index",
    "find",
}

#: ``re`` methods whose reason-bearing operand is typically an ARGUMENT, not
#: the receiver -- ``_COMPOUND_MATCH_PATTERN.match(reason)`` (a compiled
#: pattern's own method) and ``re.match(pattern, reason)`` (the module
#: function) both put ``reason`` in the argument list, never in the receiver
#: name, which is exactly the shape the original detector could not see: it
#: only ever looked at the receiver.
_REASON_REGEX_METHODS = {"match", "search", "fullmatch"}


def _name_of(node: ast.expr) -> Optional[str]:
    """Return a Name's id or an Attribute's trailing attr, else None."""
    if isinstance(node, ast.Name):
        return node.id
    if isinstance(node, ast.Attribute):
        return node.attr
    return None


def _is_reason_named(node: ast.expr) -> bool:
    """Return True when *node* is a Name/Attribute whose own name contains "reason"."""
    name = _name_of(node)
    return bool(name) and "reason" in name.lower()


def _enclosing_function_name(tree: ast.Module, target: ast.AST) -> Optional[str]:
    """Return the name of the nearest enclosing function/method of *target*, if any."""
    best: Optional[str] = None
    for node in ast.walk(tree):
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            if target in ast.walk(node):
                best = node.name
    return best


def find_reason_parsing_sites(
    toolguard_dir: Path = TOOLGUARD_DIR,
) -> List[Dict[str, object]]:
    """
    Return every production site that extracts structured meaning from a
    ``reason``-named string, excluding :data:`R3_SANCTIONED_SITES`.

    Three shapes are detected, all keyed on "does some Name/Attribute whose
    OWN name contains 'reason' (case-insensitive) appear here" -- which is why
    a local reassignment (``reason_body = resolved.reason``) is still caught,
    since the new name itself contains "reason":

    1. A :data:`_REASON_STRING_METHODS` call (``.split``, ``.rsplit``, ...) on
       a reason-named RECEIVER, e.g. ``reason.split(...)``.
    2. A :data:`_REASON_REGEX_METHODS` call (``.match``/``.search``/
       ``.fullmatch``) with a reason-named ARGUMENT anywhere in the call,
       whether the receiver is ``re`` itself or a module-level compiled
       pattern (``_COMPOUND_MATCH_PATTERN.match(reason)``) -- the original
       detector only ever looked at the receiver and missed exactly this
       shape in production once already.
    3. An ``in`` membership test against a reason-named value
       (``"  [" in reason_body``).

    KNOWN LIMIT, stated rather than silently missed: this is name-based, not
    data-flow analysis. A value split out of a reason string into a
    differently-named local (e.g. ``for part in reason.split(...): ...
    part.rsplit(...)``) is not traced past that rename -- the ``reason.split``
    call itself is still caught, but a *further* parse of ``part`` is not,
    because nothing in "part" says "this came from a reason string".
    """
    sites: List[Dict[str, object]] = []
    for py_file in iter_source_files(toolguard_dir):
        rel = relative_module_path(py_file, toolguard_dir)
        source = py_file.read_text(encoding="utf-8")
        tree = ast.parse(source, filename=str(py_file))
        lines = source.splitlines()
        for node in ast.walk(tree):
            expr = None
            if (
                isinstance(node, ast.Call)
                and isinstance(node.func, ast.Attribute)
                and node.func.attr in _REASON_STRING_METHODS
                and _is_reason_named(node.func.value)
            ):
                expr = lines[node.lineno - 1].strip()
            elif (
                isinstance(node, ast.Call)
                and isinstance(node.func, ast.Attribute)
                and node.func.attr in _REASON_REGEX_METHODS
                and any(_is_reason_named(arg) for arg in node.args)
            ):
                expr = lines[node.lineno - 1].strip()
            elif isinstance(node, ast.Compare) and any(
                isinstance(op, ast.In) for op in node.ops
            ):
                if any(_is_reason_named(c) for c in node.comparators):
                    expr = lines[node.lineno - 1].strip()
            if expr is None:
                continue
            func_name = _enclosing_function_name(tree, node)
            if (py_file.name, func_name) in R3_SANCTIONED_SITES:
                continue
            sites.append(
                {
                    "module": rel,
                    "line": node.lineno,
                    "expression": expr,
                    "function": func_name,
                }
            )
    # A single line can trip two different AST patterns (e.g. a `.split(...)`
    # call and an `in reason` check in the same conditional expression, as in
    # hook.py's `reason.split(...) if ": " in reason else None`) -- dedupe to
    # one reported site per (module, line) rather than double-counting.
    seen: Set[Tuple[str, int]] = set()
    unique_sites = []
    for site in sites:
        key = (site["module"], site["line"])
        if key in seen:
            continue
        seen.add(key)
        unique_sites.append(site)
    return unique_sites


