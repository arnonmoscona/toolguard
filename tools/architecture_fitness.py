def find_parallel_arrays(
    toolguard_dir: Path = TOOLGUARD_DIR, class_name: str = "ToolPatternLayer"
) -> List[Dict[str, object]]:
    """
    Return the ``(base, base_entries)`` field pairs defined on *class_name* --
    the parallel-array shape R2 targets (see the class's own docstring:
    "for each of the three allow/deny/ask pairs, X[i] is always the
    wrapper-stripped form of X_entries[i].pattern -- same order, same
    membership, index-for-index").
    """
    groups: List[Dict[str, object]] = []
    for py_file in iter_source_files(toolguard_dir):
        rel = relative_module_path(py_file, toolguard_dir)
        tree = ast.parse(py_file.read_text(encoding="utf-8"), filename=str(py_file))
        for node in ast.walk(tree):
            if isinstance(node, ast.ClassDef) and node.name == class_name:
                field_names = [
                    stmt.target.id
                    for stmt in node.body
                    if isinstance(stmt, ast.AnnAssign)
                    and isinstance(stmt.target, ast.Name)
                ]
                for name in field_names:
                    if name.endswith("_entries"):
                        continue
                    paired = f"{name}_entries"
                    if paired in field_names:
                        groups.append(
                            {
                                "class": class_name,
                                "module": rel,
                                "line": node.lineno,
                                "base_field": name,
                                "entries_field": paired,
                            }
                        )
    return groups


