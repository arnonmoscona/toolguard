#!/usr/bin/env python
"""
Dev-only instrument (repo-root ``tools/``, NOT shipped -- see ``pyproject.toml``'s
``[tool.hatch.build.targets.wheel] packages`` list, which does not include this
directory) that the TOO-45 architecture-refactoring loop runs every iteration.

Stdlib only -- this project's runtime carries no third-party dependency, and this
tool follows the same discipline so it never needs one either.

Every number this module prints is an INSTRUMENT, not a TARGET. A predicate or
metric going the "right" way is evidence to bring to a human or a judge subagent,
never a self-sufficient stopping condition -- see the TOO-45 execution plan,
section 7 ("Anti-gaming prohibitions") and section 8 (the two judges). In
particular ``--metrics``' fan-in figure is demonstrably misleading on this
codebase (see the ``--metrics`` docstring below) and must never be read alone.

Four modes
----------
``--layers``
    Validate every module under ``toolguard/`` against the ``[architecture]``
    block of ``.pyscn.toml`` (the single source of truth for the layer map).
    Reports completeness (every module maps to exactly one layer -- pyscn
    itself silently stops validating an unmapped module while its compliance
    score stays plausible, and never names the module; this closes that hole)
    and direction (every import that violates the from-layer's allow list).

``--predicates``
    Emit the COMPONENT diagnostics behind each TOO-45 step predicate (R1, R2,
    R3, R5, R6), plus the enrichment-footprint tracked diagnostic (not a
    predicate). Add ``--json`` for machine consumption; the judges read the
    components, not a bare boolean. Every generated file (banner-detected, see
    below) is excluded from every predicate here and named explicitly in the
    output -- a predicate only satisfiable by hand-editing generated code is a
    trap this project's own rules forbid walking into. R1 and R5 additionally
    exclude ``toolguard/parser/`` (out of scope for this ticket), also named
    explicitly, from their respective checks (R1's verdict-type/shim scan;
    R5's import-cycle check).

Generated code
    A file whose first ~10 lines carry a banner such as "generated from",
    "DO NOT EDIT", "@generated", or "autogenerated" (see
    :data:`GENERATED_FILE_MARKERS`) is detected by CONTENT, never by a
    hardcoded filename -- a hardcoded path silently stops protecting a second
    generated file the moment one is added. Excluded from ``--predicates`` and
    ``--metrics``; NOT excluded from ``--layers``, whose job is validating the
    real import graph, which a generated file is still part of.

``--metrics``
    History-based metrics from ``git log``, grouped by logical change (the
    ``TOO-nn`` ticket token in the full commit message, not by raw commit --
    grouping by ticket is what removes the commit-splitting gaming vector).

``--guard``
    The deterministic half of the loop's safety inspector: fails on an
    out-of-scope file touch, a shrinking test count, a new runtime dependency,
    or a failing lint/format/doc-link check. Also evaluates a fixed CANARY set
    through the LIVE toolguard hook binary and asserts the expected verdict
    still comes back -- the loop's own guard rules
    (``.claude/toolguard_hook.toml`` and ``~/.toolguard/rules/git.rules.toml``)
    are NOT version-controlled here (one is a symlink into an external dotfiles
    repo, left deliberately uncommitted; the other lives outside any repo
    entirely), and this project's own ``no_match_fallback = "allow_with_no_
    warnings"`` means a lost deny rule fails OPEN and SILENT -- nothing else
    would notice. Cheap, fast, no network (the canary check runs a local
    subprocess, nothing more). ``--guard-canaries-only`` runs just the canary
    check, skipping the diff/test-count/dependency/lint checks.

Usage::

    uv run python tools/architecture_fitness.py --layers
    uv run python tools/architecture_fitness.py --predicates --json
    uv run python tools/architecture_fitness.py --metrics
    uv run python tools/architecture_fitness.py --guard --since HEAD
"""

