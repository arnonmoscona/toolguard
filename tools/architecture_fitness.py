def iter_python_files(directory: Path) -> Iterable[Path]:
    """
    Yield every ``*.py`` file under *directory*, skipping ``__pycache__``.

    Deterministic order (sorted) so output is stable run to run, which matters
    for a tool a loop diffs between iterations.
    """
    yield from sorted(
        p for p in directory.rglob("*.py") if "__pycache__" not in p.parts
    )


#: Substrings (checked lowercased) that mark a file as machine-generated. Matched
#: against a BANNER near the top of the file, never a filename -- a hardcoded
#: filename check silently stops working the moment a second generated file is
#: added, which is the same failure class as the git-rules harness that once
#: validated a stale copy instead of the governing file (see the TOO-45 decision
#: log). ``toolguard/parser/bash_parser.py`` (canopy output from
#: ``bash_parser.peg``, ~6,500 lines, first line literally "This file was
#: generated from bash_parser.peg") is the known case today, but this must keep
#: working if a second generated file ever appears anywhere else in the tree.
GENERATED_FILE_MARKERS = (
    "generated from",
    "do not edit",
    "@generated",
    "autogenerated",
)

#: How many leading lines to scan for a generated-code banner. Generous enough
#: for a multi-line header comment block without reading the whole file.
_GENERATED_BANNER_SCAN_LINES = 10


def is_generated_file(py_file: Path) -> bool:
    """
    Return True when *py_file*'s first few lines carry a generated-code banner
    (see :data:`GENERATED_FILE_MARKERS`).

    Style/debt predicates (R1, R2, R3, R6) and history metrics must not judge
    generated code by the same bar as hand-written code: a predicate only
    satisfiable by hand-editing generated output is a trap, since this project's
    own rules (``.claude/rules/bash-grammar.md``) forbid exactly that edit.
    """
    try:
        with py_file.open("r", encoding="utf-8", errors="replace") as fh:
            head = "".join(
                line for _, line in zip(range(_GENERATED_BANNER_SCAN_LINES), fh)
            )
    except OSError:
        return False
    lowered = head.lower()
    return any(marker in lowered for marker in GENERATED_FILE_MARKERS)


def iter_source_files(directory: Path = TOOLGUARD_DIR) -> List[Path]:
    """
    Return every ``*.py`` file under *directory* EXCLUDING generated code.

    Used by every style/debt predicate detector (R1/R2/R3/R6) and by
    :func:`build_import_graph` (shared by R5 and every ``--metrics`` history
    figure) -- see :func:`is_generated_file` for why. NOT used by
    :func:`check_layers`, which validates the real import graph including
    generated files: their imports are still real architecture, even though
    their internal style is exempt from the debt predicates.
    """
    return [p for p in iter_python_files(directory) if not is_generated_file(p)]


def list_generated_files(directory: Path = TOOLGUARD_DIR) -> List[str]:
    """
    Return every generated ``*.py`` file under *directory*, as toolguard-relative
    dotted paths, sorted. Reported explicitly by ``--predicates``/``--metrics`` so
    an exclusion is never silent -- silent exclusion is how the pyscn layer map
    degraded in the first place (see the module docstring).
    """
    return sorted(
        relative_module_path(p, directory)
        for p in iter_python_files(directory)
        if is_generated_file(p)
    )


def generated_repo_paths(
    directory: Path = TOOLGUARD_DIR, repo_root: Path = REPO_ROOT
) -> Set[str]:
    """
    Return every generated file's path relative to *repo_root*, POSIX-style
    (``"toolguard/parser/bash_parser.py"``) -- matching the path spelling
    ``--metrics`` gets from ``git diff-tree --name-only``, so history-based
    figures can exclude generated files the same way ``--predicates``'
    detectors do, rather than counting a file nobody could have hand-edited
    toward "how coupled is this codebase".
    """
    return {
        p.resolve().relative_to(repo_root.resolve()).as_posix()
        for p in iter_python_files(directory)
        if is_generated_file(p)
    }


def relative_module_path(py_file: Path, package_root: Path = TOOLGUARD_DIR) -> str:
    """
    Return *py_file*'s dotted path relative to *package_root*, e.g.
    ``toolguard/tools/decision.py`` -> ``"tools.decision"``.

    ``__init__.py`` maps to its containing package (``toolguard/tools/__init__.py``
    -> ``"tools"``); *package_root*'s own ``__init__.py`` maps to ``""`` -- it is
    the container, not a layer member, and callers should treat that specially.
    """
    rel = py_file.resolve().relative_to(package_root.resolve())
    parts = list(rel.parts)
    if parts[-1] == "__init__.py":
        parts = parts[:-1]
    else:
        parts[-1] = parts[-1][: -len(".py")]
    return ".".join(parts)


def first_segment(rel_dotted: str) -> str:
    """Return the first dotted segment of *rel_dotted*, or ``""`` for the root."""
    return rel_dotted.split(".", 1)[0] if rel_dotted else ""


def resolve_toolguard_import(
    module_name: Optional[str], level: int, importer_rel: str
) -> Optional[str]:
    """
    Resolve an ``import``/``from`` statement to a toolguard-relative dotted path.

    Args:
        module_name: The ``module`` part of an ``ast.ImportFrom`` (``None`` for a
            bare relative ``from . import x``), or the dotted name of an
            ``ast.Import`` alias.
        level: The ``ast.ImportFrom.level`` (0 for absolute, N for N leading dots).
            ``0`` for a plain ``ast.Import``.
        importer_rel: The toolguard-relative dotted path of the importing module
            (from :func:`relative_module_path`), used to resolve relative imports.

    Returns:
        The imported module's path relative to ``toolguard`` (e.g. ``"tools.decision"``,
        or ``""`` for the ``toolguard`` package itself), or ``None`` if the import
        does not target anything inside ``toolguard`` at all (stdlib/third-party).
    """
    if level == 0:
        if module_name is None:
            return None
        if module_name == "toolguard":
            return ""
        if module_name.startswith("toolguard."):
            return module_name[len("toolguard.") :]
        return None
    # Relative import: level dots strip that many trailing segments from the
    # importer's own package (an importer that is itself a leaf module, i.e.
    # has no dot, has an implicit trailing package segment of its own dir).
    importer_parts = importer_rel.split(".") if importer_rel else []
    # A module's own package is its parts minus the module name itself.
    package_parts = importer_parts[:-1] if importer_parts else []
    # level=1 means "from the importer's own package"; each extra level strips one more.
    strip = level - 1
    base_parts = (
        package_parts[: len(package_parts) - strip]
        if strip <= len(package_parts)
        else []
    )
    if module_name:
        base_parts = base_parts + module_name.split(".")
    return ".".join(base_parts)


@dataclass(frozen=True)
class ImportEdge:
    """One import found in the AST, resolved to toolguard-relative module paths."""

    importer: str  # toolguard-relative dotted path of the file doing the import
    imported: str  # toolguard-relative dotted path of the imported module
    line: int
    is_local: bool  # True when the Import/ImportFrom node is NOT at module top level


def _is_module_level(node: ast.AST, tree: ast.Module) -> bool:
    """Return True when *node* is a direct child of the module body (not nested)."""
    return node in tree.body


def extract_toolguard_imports(
    py_file: Path, package_root: Path = TOOLGUARD_DIR
) -> List[ImportEdge]:
    """
    Parse *py_file* and return every import that resolves to another module
    under *package_root*, at ANY nesting depth (module level or function-local)
    -- a function-local import is exactly the shape of the known
    hook.py<->tools.decision cycle, so restricting to module-level imports
    would miss it.
    """
    source = py_file.read_text(encoding="utf-8")
    tree = ast.parse(source, filename=str(py_file))
    importer_rel = relative_module_path(py_file, package_root)
    edges: List[ImportEdge] = []
    for node in ast.walk(tree):
        is_local = not _is_module_level(node, tree)
        if isinstance(node, ast.Import):
            for alias in node.names:
                target = resolve_toolguard_import(alias.name, 0, importer_rel)
                if target is not None and target != importer_rel:
                    edges.append(
                        ImportEdge(importer_rel, target, node.lineno, is_local)
                    )
        elif isinstance(node, ast.ImportFrom):
            target = resolve_toolguard_import(node.module, node.level, importer_rel)
            if target is not None and target != importer_rel:
                edges.append(ImportEdge(importer_rel, target, node.lineno, is_local))
    return edges


